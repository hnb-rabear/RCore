		/// <summary>
		/// A struct to hold metadata for a Sprite, extracted from its .meta file.
		/// </summary>
		public struct SpriteInfo
		{
			public string name;
			public Vector2 pivot;
			public Vector4 border;
			public int alignment;
		}

		/// <summary>
		/// Parses the .meta file of a sprite or sprite atlas to extract the pivot, border, and alignment for all contained sprites.
		/// </summary>
		/// <param name="pSpriteFrom">A sprite from the texture asset whose .meta file should be read.</param>
		/// <returns>A dictionary mapping sprite names to their SpriteInfo metadata.</returns>
		public static Dictionary<string, SpriteInfo> GetPivotsOfSprites(Sprite pSpriteFrom)
		{
			var results = new Dictionary<string, SpriteInfo>();
			var lines = ReadMetaFile(pSpriteFrom);
			var nameLines = lines.Where(line => line.Trim().StartsWith("name:", StringComparison.OrdinalIgnoreCase)).ToList();

			// If 'name' entries exist, we assume it's a sprite atlas.
			if (nameLines.Count > 0) //SpriteFrom is inside a atlas
			{
				//Get names of all sprites inside atlas which contain spriteFrom
				var names = new List<string>();
				foreach (var line in nameLines)
				{
					string name = line.Replace("name: ", "").Trim();
					names.Add(name);
				}

				// Get alignment data for each sprite.
				var alignmentLines = lines.Where(line => line.Trim().StartsWith("alignment:", StringComparison.OrdinalIgnoreCase)).ToList();
				var alignments = new List<int>();
				for (int i = 0; i < alignmentLines.Count; i++)
				{
					if (i == 0) // Skip the global alignment setting.
						continue;
					string line = alignmentLines[i];
					var alignmentStr = line.Replace("alignment: ", "").Trim();
					alignments.Add(int.Parse(alignmentStr));
				}

				//Get pivots of all sprites inside atlas which contain spriteFrom
				var pivotLines = lines.Where(line => line.Trim().StartsWith("pivot:", StringComparison.OrdinalIgnoreCase)).ToList();
				var pivots = new List<Vector2>();
				foreach (var line in pivotLines)
				{
					var pivotStr = line.Replace("pivot: ", "").Trim();
					// Note: Assumes RVector2 is a simple serializable struct with public x, y fields.
					var pivot = JsonUtility.FromJson<RVector2>(pivotStr);
					pivots.Add(new Vector2(pivot.x, pivot.y));
				}

				// Get border data for each sprite.
				var borders = new List<Vector4>();
				var borderLines = lines.Where(line => line.Trim().StartsWith("border:", StringComparison.OrdinalIgnoreCase)).ToList();
				foreach (var line in borderLines)
				{
					var borderStr = line.Replace("border: ", "").Trim();
					// Note: Assumes RVector4 is a simple serializable struct with public x, y, z, w fields.
					var border = JsonUtility.FromJson<RVector4>(borderStr);
					borders.Add(new Vector4(border.x, border.y, border.z, border.w));
				}

				// Combine the parsed data into SpriteInfo structs.
				for (int i = 0; i < names.Count; i++)
					results.Add(names[i], new SpriteInfo
					{
						name = names[i],
						pivot = pivots[i],
						border = borders[i],
						alignment = alignments[i],
					});
			}
			else // It's a single sprite texture.
			{
				// Find the single alignment, pivot, and border properties.
				var alignmentLine = lines.First(line => line.Trim().StartsWith("alignment: ", StringComparison.OrdinalIgnoreCase));
				var alignmentStr = alignmentLine.Replace("alignment: ", "").Trim();
				var alignment = int.Parse(alignmentStr);

				var pivotLine = lines.First(line => line.Trim().StartsWith("spritePivot: ", StringComparison.OrdinalIgnoreCase));
				var pivotStr = pivotLine.Replace("spritePivot: ", "").Trim();
				var pivot = JsonUtility.FromJson<RVector2>(pivotStr);

				var borderStr = lines.First(line => line.Trim().StartsWith("spriteBorder: ", StringComparison.OrdinalIgnoreCase));
				var border = JsonUtility.FromJson<RVector4>(borderStr);

				results.Add(pSpriteFrom.name, new SpriteInfo
				{
					name = pSpriteFrom.name,
					pivot = new Vector2(pivot.x, pivot.y),
					border = new Vector4(border.x, border.y, border.z, border.w),
					alignment = alignment,
				});
			}
			return results;
		}

		private static readonly Regex m_GuidRefRegex = new Regex(@"fileID: -?\d+, guid: [0-9a-f]{32}", RegexOptions.Compiled);

		public class GuidReplaceResult
		{
			public int replaced;
			public int skipped;
			public int failed;
			public int references;
		}

		/// <summary>Returns the "fileID: X, guid: Y" text Unity writes for a reference to this object, or null.</summary>
		public static string GetGuidRef(Object pObj)
		{
			if (pObj == null || !AssetDatabase.TryGetGUIDAndLocalFileIdentifier(pObj, out string guid, out long fileId))
				return null;
			return $"fileID: {fileId}, guid: {guid}";
		}

		/// <summary>Builds old ref -> new ref text pairs. Skips null objects and pairs that are already equal.</summary>
		public static Dictionary<string, string> BuildGuidRefs(IEnumerable<(Object oldObj, Object newObj)> pMappings)
		{
			var refs = new Dictionary<string, string>();
			foreach (var (oldObj, newObj) in pMappings)
			{
				string oldRef = GetGuidRef(oldObj);
				string newRef = GetGuidRef(newObj);
				if (oldRef != null && newRef != null && oldRef != newRef)
					refs[oldRef] = newRef;
			}
			return refs;
		}

		/// <summary>Replaces every old ref in one pass (swapped pairs never chain). Returns how many refs were replaced.</summary>
		public static int ReplaceInText(ref string pContent, IReadOnlyDictionary<string, string> pRefs)
		{
			int count = 0;
			pContent = m_GuidRefRegex.Replace(pContent, match =>
			{
				if (!pRefs.TryGetValue(match.Value, out var newRef))
					return match.Value;
				count++;
				return newRef;
			});
			return count;
		}

		/// <summary>Read-only scan. Returns asset path -> number of old refs found in that file, or null if the user cancels.</summary>
		public static Dictionary<string, int> FindGuidReferences(IReadOnlyDictionary<string, string> pRefs, string[] pScopeGuids)
		{
			var result = new Dictionary<string, int>();
			if (pRefs.Count == 0)
				return result;
			// A ref ends with its 32-char guid.
			var oldGuids = new HashSet<string>(pRefs.Keys.Select(r => r.Substring(r.Length - 32)));
			try
			{
				for (int i = 0; i < pScopeGuids.Length; i++)
				{
					string path = AssetDatabase.GUIDToAssetPath(pScopeGuids[i]);
					if (string.IsNullOrEmpty(path) || AssetDatabase.IsValidFolder(path) || result.ContainsKey(path))
						continue;
					if (EditorUtility.DisplayCancelableProgressBar("Scanning references", path, (float)i / pScopeGuids.Length))
						return null; // a partial result would look complete in the preview
					if (!AssetDatabase.GetDependencies(path, false).Any(d => oldGuids.Contains(AssetDatabase.AssetPathToGUID(d))))
						continue;
					string text = File.ReadAllText(path);
					int count = ReplaceInText(ref text, pRefs);
					if (count > 0)
						result[path] = count;
				}
			}
			finally
			{
				EditorUtility.ClearProgressBar();
			}
			return result;
		}

		/// <summary>Rewrites old refs in the given files. A file with no match is skipped; a file that throws is logged and counted as failed.</summary>
		public static GuidReplaceResult ReplaceGuidReferences(IReadOnlyDictionary<string, string> pRefs, IList<string> pPaths)
		{
			var result = new GuidReplaceResult();
			AssetDatabase.SaveAssets(); // otherwise Refresh() reloads dirty assets from disk and drops their unsaved edits
			AssetDatabase.StartAssetEditing();
			try
			{
				for (int i = 0; i < pPaths.Count; i++)
				{
					string path = pPaths[i];
					EditorUtility.DisplayProgressBar("Replacing references", path, (float)i / pPaths.Count);
					try
					{
						string text = File.ReadAllText(path);
						int count = ReplaceInText(ref text, pRefs);
						if (count == 0)
						{
							result.skipped++;
							continue;
						}
						File.WriteAllText(path, text);
						result.replaced++;
						result.references += count;
					}
					catch (Exception e)
					{
						UnityEngine.Debug.LogError($"[Replace] {path}: {e.Message}");
						result.failed++;
					}
				}
			}
			finally
			{
				AssetDatabase.StopAssetEditing();
				EditorUtility.ClearProgressBar();
				AssetDatabase.Refresh();
			}
			return result;
		}

		/// <summary>
		/// Replaces every reference to the old objects with the new object in the given assets (null = all of Assets/).
		/// Returns referencing asset path -> number of refs replaced.
		/// </summary>
		public static Dictionary<string, int> SearchAndReplaceGuid<T>(List<T> oldObjects, T newObject, string[] assetGUIDs) where T : Object
		{
			assetGUIDs ??= AssetDatabase.FindAssets("t:Object", new[] { "Assets" });
			var refs = BuildGuidRefs(oldObjects.Select(o => ((Object)o, (Object)newObject)));
			var found = FindGuidReferences(refs, assetGUIDs) ?? new Dictionary<string, int>();
			if (found.Count > 0)
				ReplaceGuidReferences(refs, found.Keys.ToList());
			return found;
		}

