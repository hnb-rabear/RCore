		[Test]
		public void flush_captures_the_snapshot_before_the_new_sources_are_written()
		{
			var settings = SessionSettings();
			var confirm = SheetXCollectionExportSession.ConfirmDepthChange;
			// Flush now asks before migrating; an interactive Editor run would block on the dialog.
			SheetXCollectionExportSession.ConfirmDepthChange = _ => true;
			try
			{
				string path = CodeFolder + "/PlayerConfigCollection.cs";
				// On disk the collection is still SeparateAsset; settings now say Inline, so the
				// flush below is a depth migration and must snapshot THIS text, not what replaces it.
				const string previous =
					"/***\r\n * This script is automatically generated by SheetX.\r\n ***/\r\npublic partial class PlayerConfigCollection : SheetXConfigCollectionBase\r\n{\r\n}\r\n";
				Directory.CreateDirectory(CodeFolder);
				File.WriteAllText(path, previous);

				var binding = SheetXCollectionSettings.GetOrCreateBinding(settings, SourceId, "PlayerTable");
				binding.outputMode = SheetXSheetOutputMode.GeneratedDataClass;
				binding.collectionName = "Player";

				var session = new SheetXCollectionExportSession(settings);
				Assert.That(session.TryAddGeneratedTable(
					SourceId, "PlayerTable", new[] { "id:int" },
					new IReadOnlyList<string>[] { new[] { "1" } }, out string error), Is.True, error);
				Assert.That(session.Flush(out error), Is.True, error);

				// The flush replaced the file: the snapshot is worthless unless it was taken first.
				Assert.That(File.ReadAllText(path), Is.Not.EqualTo(previous));
				Assert.That(SheetXMigrationSnapshot.Exists, Is.True,
					"A depth change must capture a snapshot during Flush.");

				Assert.That(SheetXMigrationSnapshot.TryRestore(out error), Is.True, error);
				Assert.That(File.ReadAllText(path), Is.EqualTo(previous),
					"Capture must run before the generated sources are written.");
			}
			finally
			{
				SheetXCollectionExportSession.ConfirmDepthChange = confirm;
				SheetXMigrationSnapshot.Clear();
				Object.DestroyImmediate(settings);
			}
		}

		[Test]
		public void declining_a_depth_change_aborts_the_flush_before_anything_is_written()
		{
			var settings = SessionSettings();
			var confirm = SheetXCollectionExportSession.ConfirmDepthChange;
			var prompted = new List<string>();
			SheetXCollectionExportSession.ConfirmDepthChange = message =>
			{
				prompted.Add(message);
				return false;
			};
			try
			{
				string path = CodeFolder + "/PlayerConfigCollection.cs";
				const string previous =
					"/***\r\n * This script is automatically generated by SheetX.\r\n ***/\r\npublic partial class PlayerConfigCollection : SheetXConfigCollectionBase\r\n{\r\n}\r\n";
				Directory.CreateDirectory(CodeFolder);
				File.WriteAllText(path, previous);

				var binding = SheetXCollectionSettings.GetOrCreateBinding(settings, SourceId, "PlayerTable");
				binding.outputMode = SheetXSheetOutputMode.GeneratedDataClass;
				binding.collectionName = "Player";

				var session = new SheetXCollectionExportSession(settings);
				Assert.That(session.TryAddGeneratedTable(
					SourceId, "PlayerTable", new[] { "id:int" },
					new IReadOnlyList<string>[] { new[] { "1" } }, out string error), Is.True, error);

				Assert.That(session.Flush(out error), Is.False);
				Assert.That(error, Does.Contain("was not confirmed"));
				Assert.That(prompted, Has.Count.EqualTo(1));

				// Declining must abort ahead of every side effect: the sources on disk are untouched
				// and no snapshot was taken, so there is nothing left to roll back or clean up.
				Assert.That(File.ReadAllText(path), Is.EqualTo(previous));
				Assert.That(SheetXMigrationSnapshot.Exists, Is.False);
			}
			finally
			{
				SheetXCollectionExportSession.ConfirmDepthChange = confirm;
				SheetXMigrationSnapshot.Clear();
				Object.DestroyImmediate(settings);
			}
		}

		[Test]
		public void depth_change_prompt_is_injectable_and_names_the_collection()
		{
			var captured = new List<string>();
			var original = SheetXCollectionExportSession.ConfirmDepthChange;
			try
			{
				SheetXCollectionExportSession.ConfirmDepthChange = message =>
				{
					captured.Add(message);
					return false;
				};

				// A headless or test run must never block on EditorUtility.DisplayDialog.
				Assert.That(SheetXCollectionExportSession.ConfirmDepthChange("Player"), Is.False);
				Assert.That(captured, Has.Count.EqualTo(1));
				Assert.That(captured[0], Does.Contain("Player"));
			}
			finally
			{
				SheetXCollectionExportSession.ConfirmDepthChange = original;
			}
		}

