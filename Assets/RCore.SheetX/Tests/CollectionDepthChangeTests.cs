		[Test]
		public void peek_names_the_collections_a_pending_snapshot_would_revert()
		{
			var settings = CreateSettings(SheetXCollectionDepth.Inline);
			try
			{
				SheetXMigrationSnapshot.Clear();
				Assert.That(SheetXMigrationSnapshot.TryPeek(out var none, out _), Is.False);
				Assert.That(none, Is.Empty);

				string path = CodeFolder + "/PlayerConfigCollection.cs";
				SheetXMigrationSnapshot.Capture(
					settings,
					new[] { "Player" },
					new Dictionary<string, string> { [path] = "public partial class PlayerConfigCollection\r\n{\r\n}\r\n" });

				// The names are what a confirmation prompt shows, so a snapshot left over from an
				// earlier migration is visible as the wrong collection before anything is reverted.
				Assert.That(SheetXMigrationSnapshot.TryPeek(out var collections, out string settingsPath), Is.True);
				Assert.That(collections, Is.EqualTo(new[] { "Player" }));
				Assert.That(settingsPath, Is.Not.Null);

				// Peeking is read-only: the snapshot is still there to restore.
				Assert.That(SheetXMigrationSnapshot.Exists, Is.True);
			}
			finally
			{
				SheetXMigrationSnapshot.Clear();
				Object.DestroyImmediate(settings);
			}
		}

		[Test]
		public void restore_writes_the_original_bytes_and_never_a_bom()
		{
			var settings = CreateSettings(SheetXCollectionDepth.Inline);
			try
			{
				string path = CodeFolder + "/PlayerConfigCollection.cs";
				// Non-ASCII in a comment: a byte comparison catches an encoding change that a string
				// comparison would silently normalise away.
				const string previous =
					"/*** cấu hình ***/\r\npublic partial class PlayerConfigCollection : SheetXConfigCollectionBase\r\n{\r\n}\r\n";
				File.WriteAllText(path, previous);

				SheetXMigrationSnapshot.Capture(
					settings,
					new[] { "Player" },
					new Dictionary<string, string> { [path] = previous });
				File.WriteAllText(path, "[Serializable]\r\npublic partial class PlayerConfigCollection\r\n{\r\n}\r\n");

				Assert.That(SheetXMigrationSnapshot.TryRestore(out string error), Is.True, error);

				byte[] restored = File.ReadAllBytes(path);
				Assert.That(restored, Is.Not.Empty, "A restored source must never be left empty.");
				// The 1.8.0 release removed BOMs from generated output; a restored file gaining one
				// would no longer match what the generator emits for the same collection.
				Assert.That(restored.Length >= 3 && restored[0] == 0xEF && restored[1] == 0xBB && restored[2] == 0xBF,
					Is.False, "Restore must not introduce a UTF-8 BOM.");
				Assert.That(restored, Is.EqualTo(new UTF8Encoding(false).GetBytes(previous)));

				// The swap leaves no scratch file behind for the asset database to import as a script.
				Assert.That(File.Exists(path + ".tmp"), Is.False);
			}
			finally
			{
				SheetXMigrationSnapshot.Clear();
				Object.DestroyImmediate(settings);
			}
		}

		[Test]
		public void a_later_sweep_for_another_settings_asset_leaves_the_snapshot_alone()
		{
			// Sweep 1 failed on asset A, so the snapshot survives and A is not re-queued. Sweep 2 is
			// an unrelated export of asset B that succeeds cleanly: it must not delete A's only
			// recovery route.
			const string ownerPath = "Assets/A/SheetXSettings.asset";
			const string otherPath = "Assets/B/SheetXSettings.asset";

			Assert.That(SheetXCollectionBaker.ShouldClearSnapshot(
				false, 0, new[] { otherPath }, ownerPath), Is.False);

			// The sweep that actually re-bakes the migrated asset does retire it.
			Assert.That(SheetXCollectionBaker.ShouldClearSnapshot(
				false, 0, new[] { otherPath, ownerPath }, ownerPath), Is.True);

			// No snapshot at all: unchanged behaviour, Clear() is a no-op anyway.
			Assert.That(SheetXCollectionBaker.ShouldClearSnapshot(
				false, 0, new[] { otherPath }, null), Is.True);

			// A failure or a re-queued entry still blocks the clear, snapshot owner or not.
			Assert.That(SheetXCollectionBaker.ShouldClearSnapshot(
				true, 0, new[] { ownerPath }, ownerPath), Is.False);
			Assert.That(SheetXCollectionBaker.ShouldClearSnapshot(
				false, 1, new[] { ownerPath }, ownerPath), Is.False);
		}

