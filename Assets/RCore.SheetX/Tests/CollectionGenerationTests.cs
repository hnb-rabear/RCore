		[Test]
		public void generator_emits_data_and_matching_collection_scripts()
		{
			var settings = Settings();
			try
			{
				var files = SheetXCollectionGenerator.EmitFiles(settings, new[]
				{
					Generated("excel-b", "ShopItems", "Shop", "shopItems",
						"id:int", "tags[]:string", "reward.amount:int"),
					Existing("google-a", "Missions", "Shop", "missions", "MissionData"),
					Generated("excel-a", "GameSettings", "Global", "gameSettings", "key:string"),
				});
				string dataSource = files[SheetXCollectionGenerator.FileName];
				string globalSource = files["GlobalConfigCollection.cs"];
				string shopSource = files["ShopConfigCollection.cs"];

				Assert.That(dataSource, Does.Contain("public partial class ShopItemsSX"));
				Assert.That(dataSource, Does.Contain("public int id;"));
				Assert.That(dataSource, Does.Contain("public string[] tags;"));
				Assert.That(dataSource, Does.Contain("public Reward reward;"));
				Assert.That(dataSource, Does.Contain(
					"internal const string ShopItems = \"Assets/Game/DataConfig/Editor/Json/ShopItems.txt\";"));
				Assert.That(dataSource, Does.Not.Contain("ConfigCollection :"));

				Assert.That(shopSource, Does.Contain(
					"public partial class ShopConfigCollection : SheetXConfigCollectionBase"));
				Assert.That(shopSource, Does.Contain("public ShopItemsSX[] shopItems;"));
				Assert.That(shopSource, Does.Contain("public MissionData[] missions;"));
				Assert.That(globalSource, Does.Contain(
					"public partial class GlobalConfigCollection : GlobalConfigCollectionBase"));
				Assert.That(globalSource, Does.Contain("public ShopConfigCollection shop;"));

				Assert.That(files.Keys, Is.EqualTo(new[]
				{
					"SheetXDataCollections.cs",
					"GlobalConfigCollection.cs",
					"ShopConfigCollection.cs",
				}));
				foreach (string source in files.Values)
				{
					Assert.That(source, Does.StartWith(
						"/***\r\n * This script is automatically generated by SheetX.\r\n ***/\r\n"));
					Assert.That(source, Does.Contain("using RCore.SheetX;"));
					Assert.That(source, Does.Not.Contain("UnityEditor"));
					Assert.That(source, Does.Not.Contain("Newtonsoft"));
					Assert.That(source.Replace("\r\n", ""), Does.Not.Contain("\n"));
				}
			}
			finally
			{
				ScriptableObject.DestroyImmediate(settings);
			}
		}

