		private sealed class FailingFileOutput : ISheetXOutput
		{
			private readonly int m_failAfterWrite;
			private int m_writeCount;

			internal FailingFileOutput(int failAfterWrite)
			{
				m_failAfterWrite = failAfterWrite;
			}

			public void Write(string relativePath, string content)
			{
				m_writeCount++;
				SheetXHelper.WriteFile(
					Path.GetDirectoryName(relativePath) ?? "", Path.GetFileName(relativePath), content);
				if (m_writeCount == m_failAfterWrite)
					throw new IOException("Injected write failure");
			}
		}

